def _shpds_cabinet(code):
    """Шкаф ШПДС по шифру стандарта, с расшифровкой комплектации."""
    match = re.match(r"ШПДС\s+(МО\s+)?([0-9/\-]+)", code)
    is_mo = bool(match and match.group(1))
    numbers = (match.group(2) if match else "0-0-0").split("-")
    if is_mo:
        devices = numbers[0] if numbers else "0"
        analog = numbers[1] if len(numbers) > 1 else "0"
        kind = "маслонаполненное оборудование (МО)"
        details = "устройств ПАС: {}; аналоговые входы: {}".format(
            {"0": "нет", "1": "одно", "2": "два", "3": "три"}.get(
                devices[:1], devices),
            _SHPDS_ANALOG.get(analog[:1], analog))
        slug = "shpds-mo-" + "-".join(numbers)
    else:
        kind = _SHPDS_KIND.get(numbers[0], "контроль выключателя")
        per_phase = numbers[1] if len(numbers) > 1 else "0"
        three_phase = numbers[2] if len(numbers) > 2 else "0"
        details = ("КА с пофазным приводом: {}; КА с трёхфазным приводом: {}"
                   .format(per_phase, three_phase))
        slug = "shpds-" + "-".join(numbers)
    entry = dict(_SHPDS_GROUP)
    entry.update({
        "key": slug,
        "code": code,
        "name": kind,
        "title": "Шкаф преобразователей дискретных сигналов {}".format(code),
        "description": "{}: {}; {}.".format(code, kind, details),
        "komplets": [
            {"name": "ПДС", "type": "ПДС",
             "functions": ["дискретные входы", "дискретные выходы", "GOOSE"],
             "desc": "Устройства ПДС в комплектации {} ({})"
                     .format(code, details),
             "ieds": [{"name": "ПДС", "type": "ПДС",
                       "desc": "Преобразователь дискретных сигналов"}]},
        ],
    })
    return entry


