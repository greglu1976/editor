_CURRENT_TOKENS = (
    (r"I[аa]\d?", "Ia"), (r"I[Кк]\d?", "Ia"),
    (r"I[бb]\d?", "Ib"), (r"I[Лл]\d?", "Ib"),
    (r"I[вc]\d?", "Ic"), (r"I[Мм]\d?", "Ic"),
    (r"3I0", "3I0"), (r"I[нn]", "In"),
)
_VOLTAGE_TOKENS = (
    (r"U[аa]\d?", "Ua"), (r"U[Кк]\d?", "Ua"),
    (r"U[бb]\d?", "Ub"), (r"U[Лл]\d?", "Ub"),
    (r"U[вc]\d?", "Uc"), (r"U[Мм]\d?", "Uc"),
    (r"U[фf]", "Uф"), (r"U[нn]", "Un"),
    (r"3U0", "3U0"),
)
_ANALOG_HEAD = re.compile(
    r"(?:Таблица\s+5\.\d+\s*-\s*)?Входные\s+аналоговые\s+измерения"
    r"([^\n]*)")
_ANALOG_END = re.compile(
    r"(Таблица\s+5\.\d+|Внутренние\s+дискретные\s+цепи|"
    r"Информационные\s+сигналы)")


def _circuits(raw: str, side: str) -> list[str]:
    table = _CURRENT_TOKENS if side == "current" else _VOLTAGE_TOKENS
    found = []
    for pattern, preset in table:
        if re.search(pattern, raw) and preset not in found:
            found.append(preset)
    order = ("Ia", "Ib", "Ic", "In", "3I0") if side == "current" \
        else ("Ua", "Ub", "Uc", "U", "Un", "Uф", "3U0")
    return [item for item in order if item in found]


def parse_analog(text: str) -> list[dict]:
    """Таблицы входных аналоговых измерений раздела: блоки по ИЭУ."""
    blocks = []
    for match in _ANALOG_HEAD.finditer(text):
        tail = text[match.end():]
        # в таблице-описании есть строка-ссылка «Входные аналоговые
        # измерения  Таблица 5.3» — это не таблица с данными
        if re.match(r"\s*Таблица\s+5\.\d+", tail[:40]):
            continue
        stop = _ANALOG_END.search(tail)
        body = tail[:stop.start()] if stop else tail[:2500]
        rows = []
        pending = []
        lines = [re.sub(r"\s+", " ", item).strip()
                 for item in body.split("\n")]
        lines = [item for item in lines if item]
        header = re.compile(r"^(Таблица|Аналоговая|Испытательный|Количество|"
                            r"Примечание|Аналоговые|блок в шкафу)")
        tail_words = ("для", "на", "по", "с", "и", "в", "к", "от", "до", "из",
                      "при", "или")
        index = 0
        while index < len(lines):
            line = lines[index]
            index += 1
            hits = [hit for hit in re.finditer(r"SG\s*(\d+)", line)
                    if line[:hit.start()].rstrip()[-1:] != "("]
            if not hits:
                # перенос строки таблицы: цепи измерения могут быть выше SG
                if len(line) <= 90 and not header.match(line):
                    pending.append(line)
                    pending = pending[-2:]
                continue
            hit = hits[0]
            before = line[:hit.start()]
            if not before.strip():
                before = " ".join(pending)
            pending = []
            after = line[hit.end():]
            brackets = re.search(r"^\s*\(\s*SG\s*(\d+)\s*\)", after)
            before = re.sub(r"^\d+\s+", "", before).strip(" -–—")
            note = re.sub(r"^\s*\(\s*SG\s*\d+\s*\)", "", after)
            note = re.sub(r"^\s*\d+(?:\s*\+\s*\d+)?", "", note).strip()
            # примечание может продолжаться на следующей строке
            look = index
            while (look < len(lines) and look - index < 3
                   and note.rstrip(" ,;").split()[-1:] and
                   note.rstrip(" ,;").split()[-1].lower() in tail_words
                   and not re.search(r"SG\s*\d+", lines[look])
                   and len(lines[look]) <= 90
                   and not header.match(lines[look])):
                note = (note + " " + lines[look]).strip()
                look += 1
            rows.append({"circuits": before, "sg": int(hit.group(1)),
                         "note": note,
                         "alt": int(brackets.group(1)) if brackets else None})
        seen = set()
        unique = []
        for row in rows:
            signature = (row["circuits"], row["sg"], row["note"])
            if signature in seen:
                continue
            seen.add(signature)
            unique.append(row)
        if unique:
            blocks.append({"title": match.group(1).strip(), "rows": unique})
    return blocks


def _side_of(row: dict):
    """Сторона испытательного блока: «current», «voltage» или None."""
    raw = row["circuits"] or ""
    if re.match(r"^\s*3?I", raw):
        return "current"
    if re.match(r"^\s*3?U", raw):
        return "voltage"
    note = row["note"]
    if re.search(r"(?i)напряж|U[абвabcфн]", note):
        return "voltage"
    if re.search(r"(?i)ток|I[абвabcн]", note):
        return "current"
    return None


def test_blocks(block: dict) -> dict:
    """Испытательные блоки одного ИЭУ: количество и цепи по сторонам."""
    result = {"voltage": {"count": 0, "circuits": []},
              "current": {"count": 0, "circuits": []}}
    last_side = None
    last_circuits = {"current": [], "voltage": []}
    for row in block["rows"]:
        side = _side_of(row)
        if side is None:
            side = last_side or "current"
        last_side = side
        result[side]["count"] += 1
        found = _circuits(row["circuits"] + " " + row["note"], side)
        if not found:
            found = list(last_circuits[side])
        last_circuits[side] = found
        for preset in found:
            if preset not in result[side]["circuits"]:
                result[side]["circuits"].append(preset)
    return result


