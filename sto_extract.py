def split_circuits(raw: str) -> list[str]:
    return [item.strip() for item in re.split(r"[,;]+", raw) if item.strip()]


def section_by_number(secs: list[dict], num: int) -> dict | None:
    for section in secs:
        if section["num"] == num:
            return section
    return None


def _flatten(groups) -> list[str]:
    """Плоский список без повторов: [[a, b], [b, c]] -> [a, b, c]."""
    result = []
    for group in groups:
        items = group if isinstance(group, (list, tuple)) else [group]
        for item in items:
            if item not in result:
                result.append(item)
    return result


def _unique_by_sg(rows: list[dict]) -> list[dict]:
    """Убирает повторы строк таблицы (переносы страниц, склейка колонок)."""
    seen = set()
    unique = []
    for row in rows:
        if row["sg"] in seen:
            continue
        seen.add(row["sg"])
        unique.append(row)
    return unique


def build_entries() -> list[dict]:
    entries = []
    cache = {}
    for spec in CABINETS:
        doc_key = spec["doc"]
        if doc_key not in cache:
            cache[doc_key] = sections(load_document(doc_key))
        doc = DOCS[doc_key]
        num = int(spec["section"].split(".")[1])
        section = section_by_number(cache[doc_key], num)
        if section is None:
            raise SystemExit("Не найден раздел %s в %s" % (
                spec["section"], doc_key))

        # номер таблицы-описания («Таблица 5.N - Описание ШЭТ …») или
        # его отсутствие (в некоторых томах таблица не нумерована)
        caption = re.search(r"Таблица\s+5\.(\d+)\s*-\s*Описание",
                            section["text"])
        source = "разд. %s" % spec["section"]
        if caption:
            source += ", табл. 5.%s" % caption.group(1)

        blocks = parse_analog(section["text"])
        functions = spec["functions"]
        units = spec.get("units") or (["ИЭУ1"] if len(functions) == 1
                                      else ["ИЭУ1", "ИЭУ2"])
        unit_desc = spec.get("unit_desc") or [spec["description"]] * len(functions)

        if len(blocks) >= len(functions):
            blocks_for_units = blocks[:len(functions)]
        elif len(blocks) == 1 and len(functions) == 2 and any(
                row.get("alt") for row in blocks[0]["rows"]):
            # одна таблица на два ИЭУ: блоки ИЭУ2 указаны в скобках
            rows = _unique_by_sg(blocks[0]["rows"])
            first = {"title": blocks[0]["title"], "rows": rows}
            second = {"title": blocks[0]["title"],
                      "rows": [{"circuits": row["circuits"],
                                "sg": row["alt"], "note": row["note"],
                                "alt": None}
                               for row in rows if row.get("alt")]}
            blocks_for_units = [first, second]
        elif blocks:
            blocks_for_units = [blocks[0]] * len(functions)
        else:
            blocks_for_units = []

        komplets = []
        for index, unit_functions in enumerate(functions):
            unit = units[index] if index < len(units) else "ИЭУ%d" % (index + 1)
            desc = unit_desc[index] if index < len(unit_desc) else spec["description"]
            block = blocks_for_units[index] if index < len(blocks_for_units) else None
            kit = {
                "name": "Комплект %d" % (index + 1),
                "kind": "typical",
                "type": "МП РЗА",
                "functions": list(unit_functions),
                "desc": desc,
                "has_ied": True,
                "ieds": [{"name": unit, "type": "МП РЗА", "desc": desc}],
                "test_blocks": test_blocks(block) if block else
                {"voltage": {"count": 0, "circuits": []},
                 "current": {"count": 0, "circuits": []}},
                "tags": [TAG],
            }
            if spec.get("unit_desc"):
                kit["name"] = "Комплект %d" % (index + 1)
            komplets.append(kit)

        # Цепи из блоков, если разбор дал только счётчики — подстрахуемся
        entry = {
            "key": cabinet_key(spec["code"]),
            "standard_key": STANDARD_KEYS[doc_key],
            "code": spec["code"],
            "group": doc["group"],
            "name": spec["name"],
            "title": spec["name"],
            "description": spec.get("description") or spec["name"],
            "voltage": spec.get("voltage", ""),
            "protected": spec.get("protected", ""),
            "controlled": list(spec.get("controlled") or []),
            "its_functions": _flatten(spec.get("its_by_unit") or [spec["its"]]),
            "applicability": spec.get("applicability", ""),
            "architecture": "II тип",
            "source": source,
            "goose": True,
            "tags": [TAG],
            "standard_title": doc["title"],
            "edition": "Редакция 2 (проект)",
            "document": doc["file"],
            "komplets": komplets,
        }
        entries.append(entry)
    return entries


def cabinet_key(code: str) -> str:
    slug = re.sub(r"[^0-9A-Za-zА-Яа-яЁё]+", "-", code).strip("-").lower()
    return "draft-" + (slug or "cabinet")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--apply", action="store_true",
                        help="дописать шкафы в cabinets.json")
    parser.add_argument("--out", default=OUT_PATH)
    args = parser.parse_args(argv)

    entries = build_entries()
    payload = {
        "tag": TAG,
        "source": "Проекты СТО, раздел 4.16, редакция 2 (2023 г.)",
        "standards": [
            {"key": STANDARD_KEYS[key], "group": doc["group"],
             "title": doc["title"], "volume": doc["volume"],
             "file": doc["file"], "edition": "Редакция 2 (проект)"}
            for key, doc in DOCS.items()
        ],
        "cabinets": entries,
    }
    with open(args.out, "w", encoding="utf-8") as handle:
        json.dump(payload, handle, ensure_ascii=False, indent=2)

    total_kits = sum(len(entry["komplets"]) for entry in entries)
    print("Шкафов: %d, комплектов: %d -> %s" % (
        len(entries), total_kits, os.path.basename(args.out)))
    for entry in entries:
        counts = []
        for kit in entry["komplets"]:
            blocks = kit["test_blocks"]
            counts.append("U%d/I%d" % (blocks["voltage"]["count"],
                                       blocks["current"]["count"]))
        print("  %-14s %-4s %-52s %s" % (
            entry["code"], entry["group"], entry["name"][:52],
            ", ".join(counts)))

    if args.apply:
        import cabs                                   # noqa: WPS433 (локально)
        for entry in entries:
            cabs.save_cabinet(entry, None)
        print("Записано в cabinets.json")


if __name__ == "__main__":
    sys.exit(main())
