def pdf_pages(path: str) -> list[str]:
    if PdfReader is None:
        raise SystemExit("Нужен модуль pypdf: pip install pypdf")
    reader = PdfReader(path)
    return [(page.extract_text() or "") for page in reader.pages]


def load_document(key: str) -> str:
    doc = DOCS[key]
    path = os.path.join(HERE, doc["file"])
    if not os.path.exists(path):
        raise SystemExit("Нет файла: " + path)
    text = "\n".join(pdf_pages(path))
    if doc.get("decoded"):
        text = decode_text(text)
    # служебные маркеры страниц и колонцифры
    text = re.sub(r"===== PAGE \d+ =====\n\s*\d{0,3}\s*\n", "\n", text)
    text = re.sub(r"===== PAGE \d+ =====", "", text)
    text = re.sub(r"\n[ \t]*\d{1,3}[ \t]*\n", "\n", text)
    text = text.replace("\u00ad", "")
    return text


def body_start(lines: list[str]) -> int:
    """Индекс первой строки тела стандарта (после содержания)."""
    start = 0
    for index, line in enumerate(lines):
        if re.match(r"^5\.1\s+Перечень", line):
            start = index
    return start


def sections(text: str) -> list[dict]:
    """Разделы «5.N Шкаф …» тела стандарта с границами."""
    lines = text.split("\n")
    start = body_start(lines)
    heads = []
    for index, line in enumerate(lines):
        if index <= start:
            continue
        match = re.match(r"^(5\.(\d+))\s+(Шкаф|Комплект)", line)
        if match and "..." not in line:
            heads.append((index, match.group(1), int(match.group(2))))
    result = []
    for number, (index, label, num) in enumerate(heads):
        end = heads[number + 1][0] if number + 1 < len(heads) else len(lines)
        result.append({"num": num, "label": label, "start": index,
                       "end": end, "text": "\n".join(lines[index:end])})
    return result


