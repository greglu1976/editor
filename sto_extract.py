# ---------------------------------------------------------------------------
# Декодирование текста т. 1
# ---------------------------------------------------------------------------
# В PDF т. 1 таблица ToUnicode шрифта TimesNewRomanPSMT заполнена частично:
# для кириллических глифов она отдаёт сам номер глифа (U+023A…U+0279), из-за
# чего текст выглядит как «ȼɜɟɞɟɧɢɟ». Строчные буквы идут подряд с «а»
# (U+025A), прописные — с «А» (U+023A).
_LOWER = "абвгдежзийклмнопрстуфхцчшщъыьэюя"
_UPPER = "АБВГДЕЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯ"
_TRANSLATION = {}
for _index, _char in enumerate(_LOWER):
    _TRANSLATION[chr(0x25A + _index)] = _char
for _index, _char in enumerate(_UPPER):
    _TRANSLATION[chr(0x23A + _index)] = _char


def decode_text(text: str) -> str:
    """Раскодирует «глифовый» текст т. 1 (для остальных томов — no-op)."""
    return text.translate(str.maketrans(_TRANSLATION))


